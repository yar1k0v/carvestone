/// The block as this binary writes it: both marker lines included, `\n` line ends, a final newline.
pub fn block() -> String {
    let mut out = format!(
        "{BEGIN}\n## Stone\n\n\
         Generated by `{REFRESH}`; text outside the markers is never touched.\n\n\
         This repository keeps its tasks, docs, decisions and architecture in `stone/` and answers questions about its code from an index. \
         Agents read and change all of it through the `stone` CLI. `stone instructions` prints the workflow; \
         `stone instructions plan`, `do`, `finish`, `design` and `debug` print one topic. \
         At the start of a session, run `stone map`: it prints the components, the tasks in review and the next ready tasks.\n\n\
         | Question | Command |\n|---|---|\n"
    );
    for (question, command) in TABLE {
        out.push_str(&format!("| {question} | {command} |\n"));
    }
    out.push_str(END);
    out.push('\n');
    out
}

/// What a file holds of the block.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BlockState {
    /// No markers.
    Missing,
    /// Markers around exactly what this binary writes.
    Current,
    /// Markers around something else.
    Stale,
}

/// Byte range of the block (marker lines included, with the end line's own line ending), or the
/// sentence that says why the markers cannot be trusted.
fn locate(text: &str) -> Result<Option<(usize, usize)>, String> {
    let mut start = None;
    let mut at = 0;
    for line in text.split_inclusive('\n') {
        let end = at + line.len();
        match (line.trim(), start) {
            (BEGIN, None) => start = Some(at),
            (BEGIN, Some(_)) => return Err(format!("it has two `{BEGIN}` lines")),
            (END, Some(from)) => return Ok(Some((from, end))),
            (END, None) => return Err(format!("it has `{END}` before any `{BEGIN}`")),
            _ => {}
        }
        at = end;
    }
    match start {
        Some(_) => Err(format!("it has `{BEGIN}` but no `{END}`")),
        None => Ok(None),
    }
}

/// Whether `text` holds the block and whether it matches. `Err` names the marker problem.
pub fn state(text: &str) -> Result<BlockState, String> {
    Ok(match locate(text)? {
        None => BlockState::Missing,
        Some((from, to)) => {
            if text[from..to].replace("\r\n", "\n") == block() {
                BlockState::Current
            } else {
                BlockState::Stale
            }
        }
    })
}

/// `text` with the block added at the end, or replaced between its markers. Only those lines change,
/// and the file's own line ending is used. Text that already holds the current block comes back as it is.
pub fn apply(text: &str) -> Result<String, String> {
    let eol = if text.contains("\r\n") { "\r\n" } else { "\n" };
    let fresh = block().replace('\n', eol);
    match locate(text)? {
        Some((from, to)) => {
            // A closing marker that ends the file without a line ending keeps that.
            let tail = if text[from..to].ends_with('\n') {
                fresh.as_str()
            } else {
                fresh.trim_end_matches(['\r', '\n'])
            };
            if text[from..to] == *tail {
                return Ok(text.to_string());
            }
            Ok(format!("{}{tail}{}", &text[..from], &text[to..]))
        }
        None => {
            let mut out = text.to_string();
            if !out.is_empty() {
                if !out.ends_with('\n') {
                    out.push_str(eol);
                }
                out.push_str(eol);
            }
            out.push_str(&fresh);
            Ok(out)
        }
    }
}

/// The file that holds the block: the one with the markers, else `CLAUDE.md` when it exists, else
/// `AGENTS.md` when it exists, else `CLAUDE.md` (to be created).
pub fn target(root: &Path) -> PathBuf {
    let held = FILES.iter().map(|f| root.join(f)).find(|p| {
        std::fs::read_to_string(p)
            .ok()
            .is_some_and(|text| locate(&text).is_ok_and(|found| found.is_some()))
    });
    held.or_else(|| FILES.iter().map(|f| root.join(f)).find(|p| p.is_file()))
        .unwrap_or_else(|| root.join(FILES[0]))
}

/// What `write_agent_block` did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AgentBlock {
    /// The file name, such as `CLAUDE.md`.
    pub file: String,
    /// False when the file already held the current block.
    pub changed: bool,
}

impl Repo {
    /// Adds the block to `CLAUDE.md` or `AGENTS.md` at the repository root, or refreshes it between its markers.
    pub fn write_agent_block(&self) -> Result<AgentBlock, EngineError> {
        let lock = self.store.lock()?;
        let root = &self.store.layout.root;
        let path = target(root);
        let file = path
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let text = match std::fs::read(&path) {
            Ok(bytes) => String::from_utf8(bytes)
                .map_err(|_| EngineError::Invalid(format!("{file} is not valid UTF-8; nothing was written")))?,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(e) => return Err(EngineError::Invalid(format!("cannot read {file}: {e}"))),
        };
        let next = apply(&text).map_err(|why| {
            EngineError::Invalid(format!(
                "{file} has a broken stone block: {why}; fix the markers by hand"
            ))
        })?;
        let changed = next != text;
        if changed {
            write_atomic(&path, &next)?;
        }
        // Held to here so two writers never replace the file from the same stale read.
        drop(lock);
        Ok(AgentBlock { file, changed })
    }
}

/// Warnings for the block in `CLAUDE.md` or `AGENTS.md` under `root`: markers that do not pair, or a
/// block that differs from what this binary writes. A file without markers is the user's choice.
pub fn block_problems(root: &Path, out: &mut Vec<Problem>) {
    for name in FILES {
        let Ok(text) = std::fs::read_to_string(root.join(name)) else {
            continue;
        };
        match state(&text) {
            Ok(BlockState::Missing | BlockState::Current) => {}
            Ok(BlockState::Stale) => out.push(Problem::warning(
                name,
                marker_line(&text),
                "agent-block",
                format!("the stone block differs from what this stone writes; run `{REFRESH}` to refresh it"),
            )),
            Err(why) => out.push(Problem::warning(
                name,
                marker_line(&text),
                "agent-block",
                format!("the stone block is broken: {why}; fix the markers by hand, then run `{REFRESH}`"),
            )),
        }
    }
}

/// The 1-based line of the first marker, or 1.
fn marker_line(text: &str) -> usize {
    text.lines()
        .position(|l| matches!(l.trim(), BEGIN | END))
        .map_or(1, |n| n + 1)
}
